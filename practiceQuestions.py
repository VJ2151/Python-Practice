# Sort a list without using the keyword Sort.
l=[2,7,23,63,96,24,90,23,5,38,60,92]

for i in range(len(l)):
    for j in range(i+1,len(l)):
        if l[i]>l[j]:
            l[i],l[j]=l[j],l[i]
print(l)

